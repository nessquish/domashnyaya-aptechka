def more_shopping() -> List[Tuple]:
    """Ещё позиции списка покупок: (название, количество, единица, источник,
    куплено, товар аптечки или None, дней назад, время).

    Из товаров аптечки берутся ссылки, остальные позиции без ссылки. Источники
    чередуются по всем видам, купленных примерно каждая четвёртая.
    """
    rows = []
    for index, name in enumerate(_LINKED):
        rows.append(
            (
                name,
                1 + index % 5,
                "шт.",
                _SOURCES[1 + index % 5],
                int(index % 4 == 0),
                name,
                1 + index * 2 % 58,
                _CLOCKS[index % len(_CLOCKS)],
            )
        )
    for index, (name, unit) in enumerate(_STANDALONE):
        source = "import" if index % 3 == 0 else "manual"
        rows.append(
            (
                name,
                1 + index * 3 % 12,
                unit,
                source,
                int(index % 4 == 1),
                None,
                2 + index * 3 % 56,
                _CLOCKS[(index + 3) % len(_CLOCKS)],
            )
        )
    return rows


# Шаблоны записей истории: (действие, текст; {n} — название, {a} и {b} — числа).
_HISTORY_TEMPLATES = (
    ("product_added", "{n} · добавлен в аптечку"),
    ("product_updated", "{n} · количество изменено с {b} шт. до {a} шт."),
    ("shopping_added", "{n} · {a} шт. · добавлено в список покупок"),
    ("shopping_bought", "{n} · {a} шт. · куплено"),
    ("product_updated", "{n} · изменено: срок годности"),
    ("shopping_removed", "{n} · {a} шт. · удалено из списка покупок"),
    ("product_updated", "{n} · минимальный остаток изменён с {b} шт. до {a} шт."),
    ("product_updated", "{n} · изменено: место хранения, примечание"),
    ("product_deleted", "{n} · удалён из аптечки"),
    ("product_updated", "{n} · изменено: категория"),
)


def more_history() -> List[Tuple]:
    """Ещё записи истории: (действие, товар или None, описание, дней назад, время).

    Названия берутся из товаров, поэтому записи разные; для удалённых товаров
    ссылки нет. Дни расходятся на два месяца назад.
    """
    names = [row[0] for row in MORE_PRODUCTS] + list(_LINKED)
    rows = []
    for index in range(72):
        action, template = _HISTORY_TEMPLATES[index % len(_HISTORY_TEMPLATES)]
        name = names[(index * 7) % len(names)]
        text = template.format(n=name, a=2 + index % 9, b=1 + index % 7)
        product = None if action == "product_deleted" else name
        rows.append(
            (action, product, text, index * 5 // 6, _CLOCKS[(index * 3) % len(_CLOCKS)])
        )
    return rows
